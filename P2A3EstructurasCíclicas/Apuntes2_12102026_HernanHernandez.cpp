#include <iostream>
using namespace std;
//Imprimir los numeros del 1 al 10
//Utilizando while

int main()
{
    int cont;
    cont = 1;

    while (cont <= 10) {//Mientras
        cout << cont << endl;
        cont = cont + 1;
    }
    return 0;
}


